def pets_of(user):
    return [p for p in user.get("pets", []) if p in PETS]

def has_pet(user, pet_id):
    return pet_id in user.get("pets", [])

def best_pet(user):
    """ID самого сильного питомца игрока (или None, если питомцев нет)."""
    owned = pets_of(user)
    return max(owned, key=lambda p: PETS[p]["level"]) if owned else None

def give_pet(user, pet_id):
    """Выдаёт питомца. False — такого питомца нет или он уже у игрока."""
    if pet_id not in PETS or has_pet(user, pet_id):
        return False
    user.setdefault("pets", []).append(pet_id)
    return True

def pet_money_text(n):
    """10_000_000_000 → «10ккк», 50_000_000 → «50кк»."""
    for unit, suffix in ((10 ** 9, "ккк"), (10 ** 6, "кк")):
        if n >= unit and n % unit == 0:
            return f"{n // unit}{suffix}"
    return f"{n:,}".replace(",", " ")

